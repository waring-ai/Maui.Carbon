using System.Security.Cryptography;
using System.Text;

namespace Maui.Carbon.Generator;

/// <summary>Entry point shared by the CLI and the tests.</summary>
public static class CarbonGenerator
{
    /// <summary>
    /// Generates every <c>*.g.cs</c> file from a design folder. Keys are file names. The output always uses LF line
    /// endings (the emitters' AppendLine writes CRLF on Windows), so it is identical on every OS.
    /// </summary>
    public static IReadOnlyDictionary<string, string> Generate(string designDir)
    {
        var tokensPath = Path.Combine(designDir, "tokens.json");
        var tokens = CarbonTokens.Load(tokensPath);
        var tokenHash = Hash(ReadLf(tokensPath));

        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var (name, body) in TokenEmitter.Emit(tokens))
            files[name] = Normalize(Header($"tokens.json sha256 {tokenHash}") + body);

        var iconsDir = Path.Combine(designDir, "icons");
        if (Directory.Exists(iconsDir) && IconEmitter.IsAvailable)
        {
            var iconHash = HashFolder(iconsDir, "*.svg");
            foreach (var (name, body) in IconEmitter.Emit(iconsDir))
                files[name] = Normalize(Header($"icons/*.svg sha256 {iconHash}") + body);
        }
        return files;
    }

    /// <summary>Returns a description of every difference between <paramref name="files"/> and the folder.</summary>
    public static IReadOnlyList<string> FindDrift(IReadOnlyDictionary<string, string> files, string outputDir)
    {
        var drift = new List<string>();
        foreach (var (name, content) in files)
        {
            var path = Path.Combine(outputDir, name);
            if (!File.Exists(path)) drift.Add($"{name} is missing");
            else if (Normalize(File.ReadAllText(path)) != Normalize(content)) drift.Add($"{name} differs");
        }
        if (Directory.Exists(outputDir))
        {
            foreach (var path in Directory.GetFiles(outputDir, "*.g.cs"))
            {
                var name = Path.GetFileName(path);
                if (!files.ContainsKey(name)) drift.Add($"{name} is stale");
            }
        }
        return drift;
    }

    static string Header(string source) =>
        $"""
        // <auto-generated>
        //   Generated by tools/Maui.Carbon.Generator from design/carbon ({source}).
        //   Do not edit by hand: change the design snapshot and re-run the generator.
        // </auto-generated>
        #nullable enable

        """;

    static string Hash(byte[] bytes) => Convert.ToHexStringLower(SHA256.HashData(bytes))[..16];

    /// <summary>A text input's bytes with CRLF folded to LF, so the source hashes do not depend on the checkout.</summary>
    static byte[] ReadLf(string path)
    {
        var bytes = File.ReadAllBytes(path);
        var result = new List<byte>(bytes.Length);
        for (var i = 0; i < bytes.Length; i++)
            if (!(bytes[i] == (byte)'\r' && i + 1 < bytes.Length && bytes[i + 1] == (byte)'\n')) result.Add(bytes[i]);
        return [.. result];
    }

    static string HashFolder(string dir, string pattern)
    {
        using var sha = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        foreach (var file in Directory.GetFiles(dir, pattern).Order(StringComparer.Ordinal))
        {
            sha.AppendData(Encoding.UTF8.GetBytes(Path.GetFileName(file)));
            sha.AppendData(ReadLf(file));
        }
        return Convert.ToHexStringLower(sha.GetHashAndReset())[..16];
    }

    /// <summary>Folds CRLF to LF: generated output is always LF, and line endings never count as drift.</summary>
    static string Normalize(string text) => text.Replace("\r\n", "\n");
}

public static class RepoPaths
{
    /// <summary>Walks up from <paramref name="start"/> to the folder containing <c>Maui.Carbon.slnx</c>.</summary>
    public static string FindRoot(string start)
    {
        for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
            if (File.Exists(Path.Combine(dir.FullName, "Maui.Carbon.slnx")))
                return dir.FullName;
        throw new InvalidOperationException($"Could not find Maui.Carbon.slnx above '{start}'.");
    }
}
